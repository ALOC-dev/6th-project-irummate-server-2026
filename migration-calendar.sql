BEGIN;

ALTER TABLE dormitory_notices
    ADD COLUMN IF NOT EXISTS body_text text,
    ADD COLUMN IF NOT EXISTS body_version integer NOT NULL DEFAULT 0;

CREATE TABLE IF NOT EXISTS calendar_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    notice_id bigint REFERENCES dormitory_notices(id),
    source_type varchar(16) NOT NULL,
    title varchar(200) NOT NULL,
    category varchar(24) NOT NULL,
    audience varchar(200),
    description text,
    all_day boolean NOT NULL,
    start_at timestamptz NOT NULL,
    end_at timestamptz,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    deleted_at timestamptz,
    CONSTRAINT ck_calendar_event_interval CHECK (end_at IS NULL OR end_at > start_at),
    CONSTRAINT ck_calendar_event_all_day CHECK (NOT all_day OR end_at IS NOT NULL),
    CONSTRAINT ck_calendar_event_source CHECK (
        source_type = 'MANUAL' OR (source_type = 'AI' AND notice_id IS NOT NULL)
    )
);

CREATE INDEX IF NOT EXISTS idx_calendar_events_start ON calendar_events(start_at, id);
CREATE INDEX IF NOT EXISTS idx_calendar_events_notice ON calendar_events(notice_id);

CREATE TABLE IF NOT EXISTS calendar_extraction_jobs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    notice_id bigint NOT NULL REFERENCES dormitory_notices(id),
    body_version integer NOT NULL,
    status varchar(24) NOT NULL,
    attempt_count integer NOT NULL,
    next_attempt_at timestamptz NOT NULL,
    lease_token uuid,
    lease_expires_at timestamptz,
    result jsonb,
    last_error varchar(80),
    CONSTRAINT uk_calendar_extractions_notice_version UNIQUE (notice_id, body_version)
);

CREATE INDEX IF NOT EXISTS idx_calendar_extractions_status_next
    ON calendar_extraction_jobs(status, next_attempt_at, id);

COMMIT;
