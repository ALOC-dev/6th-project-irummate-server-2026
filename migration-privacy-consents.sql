CREATE TABLE IF NOT EXISTS privacy_consents (
    user_id BIGINT PRIMARY KEY,
    profile_collection_status VARCHAR(20) NOT NULL DEFAULT 'NOT_DECIDED',
    profile_collection_document_version VARCHAR(20),
    profile_collection_updated_at TIMESTAMPTZ,
    ai_cert_training_status VARCHAR(20) NOT NULL DEFAULT 'NOT_DECIDED',
    ai_cert_training_document_version VARCHAR(20),
    ai_cert_training_updated_at TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS privacy_consent_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    consent_type VARCHAR(50) NOT NULL,
    action VARCHAR(20) NOT NULL,
    document_version VARCHAR(20) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL
);

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'fk_privacy_consents_user' AND conrelid = 'privacy_consents'::regclass
    ) THEN
        ALTER TABLE privacy_consents
            ADD CONSTRAINT fk_privacy_consents_user FOREIGN KEY (user_id) REFERENCES users(id);
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'fk_privacy_consent_history_user' AND conrelid = 'privacy_consent_history'::regclass
    ) THEN
        ALTER TABLE privacy_consent_history
            ADD CONSTRAINT fk_privacy_consent_history_user FOREIGN KEY (user_id) REFERENCES users(id);
    END IF;
END $$;

CREATE INDEX IF NOT EXISTS idx_privacy_consent_history_latest
    ON privacy_consent_history (user_id, consent_type, id DESC);

