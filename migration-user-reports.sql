-- 배포 대상 PostgreSQL DB에 적용할 신고 테이블. 접수·목록·상세 조회에 사용한다.
CREATE TABLE IF NOT EXISTS user_reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporter_id BIGINT NOT NULL,
    reported_id BIGINT NOT NULL,
    source_type VARCHAR(30) NOT NULL,
    reason TEXT NOT NULL,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT ck_user_reports_not_self CHECK (reporter_id <> reported_id),
    CONSTRAINT fk_user_reports_reporter FOREIGN KEY (reporter_id) REFERENCES users(id),
    CONSTRAINT fk_user_reports_reported FOREIGN KEY (reported_id) REFERENCES users(id)
);

CREATE INDEX IF NOT EXISTS idx_user_reports_created_id
    ON user_reports (created_at DESC, id DESC);
