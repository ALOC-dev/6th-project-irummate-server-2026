-- 기존 수동 SQL 마이그레이션 방식. 대상 PostgreSQL DB에서 배포 전에 실행한다.
-- Hibernate ddl-auto=update도 새 테이블을 생성하지만 기존 테이블의 CHECK 보강은 이 SQL로 관리한다.
CREATE TABLE IF NOT EXISTS user_blocks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    blocker_id BIGINT NOT NULL,
    blocked_id BIGINT NOT NULL,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT uk_user_blocks_pair UNIQUE (blocker_id, blocked_id),
    CONSTRAINT ck_user_blocks_not_self CHECK (blocker_id <> blocked_id),
    CONSTRAINT fk_user_blocks_blocker FOREIGN KEY (blocker_id) REFERENCES users(id),
    CONSTRAINT fk_user_blocks_blocked FOREIGN KEY (blocked_id) REFERENCES users(id)
);

-- 정방향 조회는 UNIQUE 인덱스, 역방향 조회는 아래 인덱스를 사용한다.
CREATE INDEX IF NOT EXISTS idx_user_blocks_reverse ON user_blocks (blocked_id, blocker_id);
