-- Additive, optional pre-deployment DDL. Hibernate ddl-auto=update also creates this new table.
-- Does not change existing tables or delete data. Run against the intended database only.
CREATE TABLE IF NOT EXISTS dormitory_notices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    external_id VARCHAR(100) NOT NULL,
    title VARCHAR(500) NOT NULL,
    published_at DATE NOT NULL,
    url TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_dormitory_notices_external_id UNIQUE (external_id)
);
CREATE INDEX IF NOT EXISTS idx_dormitory_notices_published_id
    ON dormitory_notices (published_at DESC, id DESC);
